"""Every rule the database must defend on its own, attempted and expected to fail.

modelo-datos section 6 asks for one test per invariant that tries to violate it.
A constraint nobody tests is a constraint that can quietly stop existing: it is
one careless autogenerated migration away from being dropped, and nothing else
in the system would notice until data was already wrong.
"""

import pytest
from sqlalchemy import Connection, text
from sqlalchemy.exc import IntegrityError

INSERT_ACCOUNT = (
    "INSERT INTO account (name, email, password_hash) VALUES (:n, :e, 'not-a-real-hash')"
)


# --- identity ---------------------------------------------------------------


def test_email_must_be_stored_lowercase(db: Connection) -> None:
    """The CHECK is what makes a plain UNIQUE equivalent to unique on lower(email)."""
    with pytest.raises(IntegrityError, match="ck_account_email_lowercase"):
        db.execute(text(INSERT_ACCOUNT), {"n": "Ana", "e": "Ana@Test.com"})


def test_email_is_unique_even_against_deactivated_accounts(db: Connection) -> None:
    """Identity is global: reusing it makes the original person's return ambiguous."""
    db.execute(text(INSERT_ACCOUNT), {"n": "Ana", "e": "ana@test.com"})
    db.execute(text("UPDATE account SET is_active = false WHERE email = 'ana@test.com'"))

    with pytest.raises(IntegrityError, match="uq_account_email"):
        db.execute(text(INSERT_ACCOUNT), {"n": "Otra Ana", "e": "ana@test.com"})


