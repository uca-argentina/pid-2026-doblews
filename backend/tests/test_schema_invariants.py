# --- timestamps -------------------------------------------------------------


def test_updated_at_is_maintained_by_the_database(db: Connection, world) -> None:
    """The trigger wins over whatever the writer says, which is the whole point.

    now() is the transaction timestamp, so created_at and updated_at are equal
    inside a single transaction and comparing them proves nothing. Writing an
    old value and finding it overwritten does.
    """
    db.execute(
        text("UPDATE firm SET name = 'Norte SRL', updated_at = '2000-01-01' WHERE id = :f"),
        {"f": world.firm_a},
    )

    overwritten = db.execute(
        text("SELECT updated_at = now() FROM firm WHERE id = :f"),
        {"f": world.firm_a},
    ).scalar_one()
    assert overwritten is True


# --- the system catalogue ---------------------------------------------------
#
# T-04's four tables. The unit is looked up by code rather than passed in: which
# one it is never matters here, only that it exists.
#
# The names below are deliberately not trade names. These tables arrive seeded,
# and a test that inserts "Ladrillo común" would collide with the catalogue's own
# row — turning a rule about the schema into a fact about the seed's contents.

INSERT_RESOURCE = (
    "INSERT INTO resource (type, name, unit_of_measure_id, reference_price, currency)"
    " VALUES (:type, :name, (SELECT id FROM unit_of_measure WHERE code = 'u'), :price, :currency)"
)

INSERT_RECIPE = (
    "INSERT INTO recipe (name, unit_of_measure_id, firm_id)"
    " VALUES (:name, (SELECT id FROM unit_of_measure WHERE code = 'm2'), :firm) RETURNING id"
)


def new_resource(db: Connection, name: str = "Material de prueba", **overrides) -> int:
    """A valid material, plus whatever the caller wants wrong about it."""
    row = {"type": "material", "name": name, "price": 230, "currency": "ARS"} | overrides
    db.execute(text(INSERT_RESOURCE), row)
    return db.execute(
        text("SELECT id FROM resource WHERE name = :name ORDER BY id DESC LIMIT 1"),
        {"name": name},
    ).scalar_one()


def new_recipe(db: Connection, name: str = "Receta de prueba", firm: int | None = None) -> int:
    """A general recipe, or a firm's own when firm is given (HU-9)."""
    return db.execute(text(INSERT_RECIPE), {"name": name, "firm": firm}).scalar_one()


