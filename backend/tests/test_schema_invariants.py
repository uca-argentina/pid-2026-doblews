"""Every rule the database must defend on its own, attempted and expected to fail.

modelo-datos section 6 asks for one test per invariant that tries to violate it.
A constraint nobody tests is a constraint that can quietly stop existing: it is
one careless autogenerated migration away from being dropped, and nothing else
in the system would notice until data was already wrong.
"""

import pytest
from sqlalchemy import Connection, text
from sqlalchemy.exc import IntegrityError

INSERT_ACCOUNT = (
    "INSERT INTO account (name, email, password_hash) VALUES (:n, :e, 'not-a-real-hash')"
)


# --- identity ---------------------------------------------------------------


def test_email_must_be_stored_lowercase(db: Connection) -> None:
    """The CHECK is what makes a plain UNIQUE equivalent to unique on lower(email)."""
    with pytest.raises(IntegrityError, match="ck_account_email_lowercase"):
        db.execute(text(INSERT_ACCOUNT), {"n": "Ana", "e": "Ana@Test.com"})


def test_email_is_unique_even_against_deactivated_accounts(db: Connection) -> None:
    """Identity is global: reusing it makes the original person's return ambiguous."""
    db.execute(text(INSERT_ACCOUNT), {"n": "Ana", "e": "ana@test.com"})
    db.execute(text("UPDATE account SET is_active = false WHERE email = 'ana@test.com'"))

    with pytest.raises(IntegrityError, match="uq_account_email"):
        db.execute(text(INSERT_ACCOUNT), {"n": "Otra Ana", "e": "ana@test.com"})


# --- a role can only be granted in its own scope ----------------------------


def test_a_firm_role_cannot_be_granted_on_the_platform(db, role_id, world) -> None:
    with pytest.raises(IntegrityError, match="fk_platform_member_role_id"):
        db.execute(
            text(
                "INSERT INTO platform_member (account_id, role_id, role_scope)"
                " VALUES (:a, :r, 'platform')"
            ),
            {"a": world.account_a, "r": role_id[("owner", "firm")]},
        )


def test_a_project_role_cannot_be_granted_in_a_firm_roster(db, role_id, world) -> None:
    with pytest.raises(IntegrityError, match="fk_firm_member_role_id"):
        db.execute(
            text(
                "INSERT INTO firm_member (firm_id, account_id, role_id, role_scope)"
                " VALUES (:f, :a, :r, 'firm')"
            ),
            {"f": world.firm_b, "a": world.account_a, "r": role_id[("lead", "project")]},
        )


def test_a_platform_role_cannot_be_granted_in_a_project(db, role_id, world) -> None:
    with pytest.raises(IntegrityError, match="fk_project_member_role_id"):
        db.execute(
            text(
                "INSERT INTO project_member"
                " (project_id, account_id, firm_id, role_id, role_scope, role_code)"
                " VALUES (:p, :a, :f, :r, 'project', 'support')"
            ),
            {
                "p": world.project_a,
                "a": world.account_a,
                "f": world.firm_a,
                "r": role_id[("support", "platform")],
            },
        )


def test_the_scope_discriminator_cannot_be_tampered_with(db, role_id, world) -> None:
    """role_scope is pinned by a CHECK, so the composite FK cannot be dodged."""
    with pytest.raises(IntegrityError, match="ck_project_member_role_scope_fixed"):
        db.execute(
            text(
                "INSERT INTO project_member"
                " (project_id, account_id, firm_id, role_id, role_scope, role_code)"
                " VALUES (:p, :a, :f, :r, 'firm', 'owner')"
            ),
            {
                "p": world.project_a,
                "a": world.account_a,
                "f": world.firm_a,
                "r": role_id[("owner", "firm")],
            },
        )


def test_a_role_cannot_be_wired_to_a_permission_of_another_scope(
    db: Connection, role_id, permission_id
) -> None:
    """support + project.edit, tried with both scope values that could bridge them.

    Neither works: one FK reads the scope against role, the other against
    permission, and they share the column. This is the reason support cannot be
    given content permissions by a mistyped seed.
    """
    support = role_id[("support", "platform")]
    project_edit = permission_id[("project.edit", "project")]

    for scope in ("platform", "project"):
        savepoint = db.begin_nested()
        with pytest.raises(IntegrityError, match="fk_role_permission_"):
            db.execute(
                text(
                    "INSERT INTO role_permission (role_id, permission_id, scope)"
                    " VALUES (:r, :p, :s)"
                ),
                {"r": support, "p": project_edit, "s": scope},
            )
        savepoint.rollback()


# --- tenant isolation -------------------------------------------------------


def test_a_project_member_must_be_on_that_firms_roster(db, world, add_project_member) -> None:
    """account_b exists, but belongs to firm B's roster only."""
    with pytest.raises(IntegrityError, match="fk_project_member_firm_id"):
        add_project_member(world.project_a, world.account_b, world.firm_a, "lead")


def test_a_membership_cannot_point_at_another_firms_project(db, world, add_project_member) -> None:
    """The gravest isolation failure a multi-tenant product can have.

    project_b belongs to firm B, so claiming it under firm A's id is refused by
    the composite FK, with no validation in Python anywhere.
    """
    with pytest.raises(IntegrityError, match="fk_project_member_project_id"):
        add_project_member(world.project_b, world.account_a, world.firm_a, "lead")


# --- one lead and one client per project ------------------------------------


def test_a_project_has_at_most_one_lead(db, world, add_project_member) -> None:
    add_project_member(world.project_a, world.account_a, world.firm_a, "lead")

    with pytest.raises(IntegrityError, match="uq_project_member_lead"):
        add_project_member(world.project_a, world.account_a2, world.firm_a, "lead")


def test_a_project_has_at_most_one_client(db, world, add_project_member) -> None:
    add_project_member(world.project_a, world.account_a, world.firm_a, "client")

    with pytest.raises(IntegrityError, match="uq_project_member_client"):
        add_project_member(world.project_a, world.account_a2, world.firm_a, "client")


def test_the_limit_is_per_project_and_per_role(db, world, add_project_member) -> None:
    """Guards the WHERE of the partial indexes, which is easy to lose in a rewrite.

    A lead in each project is fine, and so are several collaborators in one
    project: the index only sees the rows its condition matches.
    """
    add_project_member(world.project_a, world.account_a, world.firm_a, "lead")
    add_project_member(world.project_b, world.account_b, world.firm_b, "lead")
    add_project_member(world.project_a, world.account_a2, world.firm_a, "collaborator")

    total = db.execute(text("SELECT count(*) FROM project_member")).scalar_one()
    assert total == 3


# --- timestamps -------------------------------------------------------------


def test_updated_at_is_maintained_by_the_database(db: Connection, world) -> None:
    """The trigger wins over whatever the writer says, which is the whole point.

    now() is the transaction timestamp, so created_at and updated_at are equal
    inside a single transaction and comparing them proves nothing. Writing an
    old value and finding it overwritten does.
    """
    db.execute(
        text("UPDATE firm SET name = 'Norte SRL', updated_at = '2000-01-01' WHERE id = :f"),
        {"f": world.firm_a},
    )

    overwritten = db.execute(
        text("SELECT updated_at = now() FROM firm WHERE id = :f"),
        {"f": world.firm_a},
    ).scalar_one()
    assert overwritten is True
