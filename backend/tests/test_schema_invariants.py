def test_the_scope_discriminator_cannot_be_tampered_with(db, role_id, world) -> None:
    """role_scope is pinned by a CHECK, so the composite FK cannot be dodged."""
    with pytest.raises(IntegrityError, match="ck_project_member_role_scope_fixed"):
        db.execute(
            text(
                "INSERT INTO project_member"
                " (project_id, account_id, firm_id, role_id, role_scope, role_code)"
                " VALUES (:p, :a, :f, :r, 'firm', 'owner')"
            ),
            {
                "p": world.project_a,
                "a": world.account_a,
                "f": world.firm_a,
                "r": role_id[("owner", "firm")],
            },
        )


def test_a_role_cannot_be_wired_to_a_permission_of_another_scope(
    db: Connection, role_id, permission_id
) -> None:
    """support + project.edit, tried with both scope values that could bridge them.

    Neither works: one FK reads the scope against role, the other against
    permission, and they share the column. This is the reason support cannot be
    given content permissions by a mistyped seed.
    """
    support = role_id[("support", "platform")]
    project_edit = permission_id[("project.edit", "project")]

    for scope in ("platform", "project"):
        savepoint = db.begin_nested()
        with pytest.raises(IntegrityError, match="fk_role_permission_"):
            db.execute(
                text(
                    "INSERT INTO role_permission (role_id, permission_id, scope)"
                    " VALUES (:r, :p, :s)"
                ),
                {"r": support, "p": project_edit, "s": scope},
            )
        savepoint.rollback()


